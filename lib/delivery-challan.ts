/**
 * Delivery challans — Super Admin's proof of delivery — without a database.
 * See plans/OF-DELIVERY-CHALLAN-proof-of-delivery.md.
 *
 * The accepted file types, the private storage key shape, the file-name rule
 * and how a file is served are stated here once; the upload route, the
 * delivery route, the read routes and the database check all follow them.
 */

/** The largest challan accepted, after an image is re-encoded. Matches `order_delivery_challans_size_ck`. */
export const MAX_DELIVERY_CHALLAN_BYTES = 4 * 1024 * 1024

/** The form value that sends an upload to the challan store rather than the catalogue. */
export const DELIVERY_CHALLAN_UPLOAD_PURPOSE = "delivery-challan"

export const DELIVERY_CHALLAN_CONTENT_TYPES = ["image/jpeg", "image/png", "image/webp", "application/pdf"] as const
export type DeliveryChallanContentType = (typeof DELIVERY_CHALLAN_CONTENT_TYPES)[number]

export type DeliveryChallanExtension = "jpg" | "png" | "webp" | "pdf"

const EXTENSION_BY_TYPE: Record<DeliveryChallanContentType, DeliveryChallanExtension> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
  "application/pdf": "pdf",
}

const TYPE_BY_EXTENSION: Record<DeliveryChallanExtension, DeliveryChallanContentType> = {
  jpg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
  pdf: "application/pdf",
}

/** What the file picker offers. The server decides by content, never by this. */
export const DELIVERY_CHALLAN_ACCEPT = ".jpg,.jpeg,.png,.webp,.pdf,image/jpeg,image/png,image/webp,application/pdf"

export function isDeliveryChallanContentType(value: unknown): value is DeliveryChallanContentType {
  return typeof value === "string" && (DELIVERY_CHALLAN_CONTENT_TYPES as readonly string[]).includes(value)
}

export function deliveryChallanExtensionFor(type: DeliveryChallanContentType): DeliveryChallanExtension {
  return EXTENSION_BY_TYPE[type]
}

/**
 * Keys are generated by the server and never derived from input, so the read
 * route can demand this exact shape. The same pattern is the database check.
 */
export const DELIVERY_CHALLAN_KEY_PREFIX = "delivery-challan"
const KEY_PATTERN =
  /^delivery-challan\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp|pdf)$/

export function isDeliveryChallanKey(value: unknown): value is string {
  return typeof value === "string" && KEY_PATTERN.test(value)
}

/** The content type a stored key implies, or null for a key this module did not make. */
export function contentTypeForDeliveryChallanKey(key: string): DeliveryChallanContentType | null {
  if (!isDeliveryChallanKey(key)) return null
  const extension = key.slice(key.lastIndexOf(".") + 1) as DeliveryChallanExtension
  return TYPE_BY_EXTENSION[extension]
}

/**
 * The uploader's file name, made safe to store and to show: no path, no
 * control or quote characters, at most 120 characters, and ending in the
 * extension the *content* was found to be — whatever the browser claimed.
 */
export function sanitizeDeliveryChallanFileName(raw: unknown, extension: DeliveryChallanExtension): string {
  const base = typeof raw === "string" ? raw.split(/[\\/]/).pop() ?? "" : ""
  const withoutExtension = base.replace(/\.[^.]*$/, "")
  const cleaned = withoutExtension
    .normalize("NFKC")
    .replace(/[^\p{L}\p{N} ._()-]+/gu, "_")
    .replace(/\s+/g, " ")
    .replace(/^[ ._-]+|[ ._-]+$/g, "")
    .slice(0, 120)
  return `${cleaned || "delivery-challan"}.${extension}`
}

/**
 * How a challan is handed to the browser. A PDF is always a download — it is
 * not re-encoded, so it never renders inside the application's origin. An
 * image (re-encoded through sharp) may be shown inline.
 */
export function deliveryChallanContentDisposition(type: DeliveryChallanContentType, fileName: string): string {
  const disposition = type === "application/pdf" ? "attachment" : "inline"
  const ascii = fileName.replace(/[^\x20-\x7e]/g, "_").replace(/["\\]/g, "_")
  return `${disposition}; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(fileName)}`
}
